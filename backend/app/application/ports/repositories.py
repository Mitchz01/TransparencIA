class WebhookDeliveryRepository(Protocol):
    def seen(self, delivery_id: str) -> bool:
        """True if a delivery with this id was already received (FR-003)."""
        ...
    def add(self, delivery: WebhookDelivery) -> WebhookDelivery: ...
