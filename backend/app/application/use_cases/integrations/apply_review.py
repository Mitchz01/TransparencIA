"""UC-11 · Apply an approved `request_review` proposal (spec 007, US4, FR-017).

Registered in spec 005's applier registry. Requests the reviews and posts the agent's
comment, marked as generated by an agent. Each step done is saved in the proposal's
result, so a retry after a failure doesn't post the comment twice."""

from app.application.ports.code_host import CodeHostFactory
from app.application.ports.event_bus import EventBus
from app.application.ports.unit_of_work import UnitOfWorkFactory
from app.domain.errors import ProposalNotFound, RepositoryNotConnected
from app.domain.events import EventRef, ReviewRequested
from app.domain.integrations import OwnWrite, OwnWriteAction, ReviewToRequest, agent_comment


class ApplyReview:
    def __init__(self, uow_factory: UnitOfWorkFactory, bus: EventBus, code_hosts: CodeHostFactory):
        self._uow_factory = uow_factory
        self._bus = bus
        self._code_hosts = code_hosts

    async def execute(self, proposal_id: int) -> None:
        with self._uow_factory() as uow:
            proposal = uow.proposals.get(proposal_id)
            if proposal is None:
                raise ProposalNotFound(proposal_id)
            project = uow.projects.get(proposal.project_id)
        content = ReviewToRequest.model_validate(proposal.final_content)
        if project is None or project.repository is None or project.repository.lower() != content.repository.lower():
            raise RepositoryNotConnected(proposal.project_id)
        host = self._code_hosts(project.github_token)
        done = dict(proposal.result or {})
        reviewers = [r.github_username for r in content.reviewers]

        if reviewers and not done.get("review_requested"):
            await host.request_review(content.repository, content.pr_number, reviewers)
            self._save_step(proposal_id, content, done, "review_requested", "review_requested")
        if not done.get("commented"):
            await host.comment_on_pull_request(content.repository, content.pr_number, agent_comment(content.comment, proposal_id))
            self._save_step(proposal_id, content, done, "commented", "commented")

        asked = ", ".join(f"@{r}" for r in reviewers)
        await self._bus.publish(
            ReviewRequested(
                project_id=project.id,
                summary=(f"Requested reviews from {asked} and posted" if asked else "Posted")
                + f" the agent's review on PR #{content.pr_number} (proposal #{proposal_id})",
                ref=EventRef(kind="proposal", id=proposal_id),
                proposal_id=proposal_id,
                pr_number=content.pr_number,
                reviewers=reviewers,
            )
        )

    def _save_step(self, proposal_id: int, content: ReviewToRequest, done: dict, step: str, action: OwnWriteAction) -> None:
        done[step] = True
        with self._uow_factory() as uow:
            uow.own_writes.add(OwnWrite(repository=content.repository, number=content.pr_number, action=action))
            current = uow.proposals.get(proposal_id)
            if current is not None:
                current.result = dict(done)
                uow.proposals.save(current)
            uow.commit()
